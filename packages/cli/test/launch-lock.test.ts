/**
 * Check 6 `run-directory-free` reads the lock through EP-13 (F123-FR-021,
 * F123-FR-022): a live lock attaches, a dead owner's lock is `stale-lock`, a
 * lock this engine did not write is `foreign-lock` — never `already-running`
 * for either — and a dry run and a run agree on all of them.
 */
import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { launchCommand, type LaunchCommandDeps } from "../src/commands/launch.ts";
import { unlockCommand } from "../src/commands/unlock.ts";
import {
  LAUNCH_CHECK_REFUSALS,
  checkRunDirectoryFree,
  decisionOfRefusal,
  isLaunchCheckRefusal,
  type LaunchCheckContext,
} from "../../pipeline/src/launch-checks/checks.ts";
import type { WorkspaceLockInspection } from "../../runtime/src/lock/inspect.ts";
import { verbRowOf } from "../src/router/verbs.ts";

const ORCHESTRATOR_LINE = "20261106-232038-3905018 2026-11-06T23:20:38+04:00\n";

type Fixture = { root: string; controlRoot: string; launcher: string; dispose(): void };

/** A workspace with one pipeline contract and one launcher, for both modes. */
function fixture(): Fixture {
  const root = mkdtempSync(join(tmpdir(), "launch-lock-"));
  const controlRoot = join(root, ".specstride");
  mkdirSync(join(controlRoot, "state", "pipeline", "p1"), { recursive: true });
  writeFileSync(join(controlRoot, "state", "pipeline", "p1", "contract"), "{}\n");
  const launcher = join(root, "launcher.mjs");
  writeFileSync(launcher, "// generated by specstride\n");
  return {
    root,
    controlRoot,
    launcher,
    dispose: () => rmSync(root, { recursive: true, force: true }),
  };
}

/** Checks 1 to 5 pass; check 6 is left to the lock on disk. */
function passingContext(f: Fixture): LaunchCheckContext {
  return {
    launcherPath: f.launcher,
    contractValidation: { status: "validated" },
    repoRoot: f.root,
    authorizedRoots: [f.root],
    syntaxProbe: () => ({ ok: true }),
    dryRun: () => ({ exitCode: 0, output: "" }),
    flags: {},
  };
}

type Run = { exit: number; lines: string[]; handshakeCalled: boolean };

async function both(
  f: Fixture,
  extra: Partial<LaunchCommandDeps> = {},
): Promise<{ dry: Run; run: Run }> {
  const go = async (mode: "dry-run" | "run"): Promise<Run> => {
    const lines: string[] = [];
    let handshakeCalled = false;
    const result = await launchCommand(["--mode", mode, "--launcher", f.launcher], {
      print: (line) => lines.push(line),
      controlRoot: f.controlRoot,
      workspaceRealPath: f.root,
      launchCheckContext: passingContext(f),
      dryRun: () => ({ exit: 0, lines: ["[DRY-RUN] ok"] }) as never,
      handshake: async () => {
        handshakeCalled = true;
        return { line: "started", exit: 0, record: null } as never;
      },
      ...extra,
    });
    return { exit: result.exit, lines, handshakeCalled };
  };
  return { dry: await go("dry-run"), run: await go("run") };
}

const stub =
  (inspection: Omit<WorkspaceLockInspection, "path" | "because">) =>
  async (): Promise<WorkspaceLockInspection> => ({ path: "lock", because: "stub", ...inspection });

test("the closed set of row 13 holds the two new lock reasons, and only already-running attaches", () => {
  assert.equal(LAUNCH_CHECK_REFUSALS.length, 13);
  for (const reason of ["stale-lock", "foreign-lock"]) {
    assert.ok(isLaunchCheckRefusal(reason), reason);
    assert.equal(decisionOfRefusal(reason), "refuse");
  }
  assert.equal(decisionOfRefusal("already-running"), "attach");
});

test("check 6 maps held, stale and foreign to three different reasons", () => {
  const base = { flags: {} } as unknown as LaunchCheckContext;
  const of = (state: "free" | "held" | "stale" | "foreign"): string | undefined => {
    const outcome = checkRunDirectoryFree({ ...base, lock: { state, detail: "owner=x age=1s" } });
    return outcome.status === "pass" ? "pass" : outcome.reason;
  };
  assert.equal(of("free"), "pass");
  assert.equal(of("held"), "already-running");
  assert.equal(of("stale"), "stale-lock");
  assert.equal(of("foreign"), "foreign-lock");
  // The boolean of the old context still reads as before.
  assert.equal(checkRunDirectoryFree({ ...base, lockHeld: true }).status, "fail");
});

test("no lock: the dry run passes and the run launches", async () => {
  const f = fixture();
  try {
    const { dry, run } = await both(f);
    assert.equal(dry.exit, 0);
    assert.equal(run.exit, 0);
    assert.equal(run.handshakeCalled, true);
  } finally {
    f.dispose();
  }
});

test("the orchestrator's stale lock file: foreign-lock in both modes, never already-running", async () => {
  const f = fixture();
  try {
    writeFileSync(join(f.controlRoot, "lock"), ORCHESTRATOR_LINE);
    const { dry, run } = await both(f);
    for (const one of [dry, run]) {
      assert.equal(one.exit, 24);
      assert.equal(one.handshakeCalled, false);
      const refusal = one.lines.find((line) => line.startsWith("[SPECSTRIDE-REFUSE]")) ?? "";
      assert.match(refusal, /reason=foreign-lock owner=orchestrator run=20261106-232038-3905018/);
      assert.match(refusal, /specstride unlock --stale/);
      assert.doesNotMatch(refusal, /already-running/);
    }
  } finally {
    f.dispose();
  }
});

test("a dead owner's lock: stale-lock in both modes", async () => {
  const f = fixture();
  try {
    const { dry, run } = await both(f, {
      inspectLock: stub({
        state: "stale",
        owner: "specstride",
        run: "run-old",
        pid: 42,
        ageSeconds: 7200,
      }),
    });
    for (const one of [dry, run]) {
      assert.equal(one.exit, 24);
      assert.equal(one.handshakeCalled, false);
      assert.match(
        one.lines.join("\n"),
        /reason=stale-lock owner=specstride run=run-old pid=42 age=2h/,
      );
    }
  } finally {
    f.dispose();
  }
});

test("a live owner's lock: both modes attach to the run that lives, and nothing is started", async () => {
  const f = fixture();
  try {
    const { dry, run } = await both(f, {
      inspectLock: stub({ state: "held", owner: "specstride", run: "run-live", pid: 7 }),
    });
    // F100-FR-160 — `attached` exits 4, the supervisor's code for `attach`.
    assert.equal(dry.exit, 4);
    assert.equal(run.exit, 4);
    assert.equal(run.handshakeCalled, false);
    for (const one of [dry, run]) {
      assert.match(one.lines.join("\n"), /\[SPECSTRIDE-LAUNCH\].*run=run-live/);
      assert.doesNotMatch(one.lines.join("\n"), /SPECSTRIDE-REFUSE/);
    }
  } finally {
    f.dispose();
  }
});

test("`unlock --stale` moves a dead orchestrator lock to backups and refuses a bad call", async () => {
  const f = fixture();
  try {
    const lock = join(f.controlRoot, "lock");
    writeFileSync(lock, ORCHESTRATOR_LINE);
    const lines: string[] = [];
    const place = { controlRoot: f.controlRoot, workspaceRealPath: f.root };
    assert.equal(await unlockCommand([], place, (l) => lines.push(l)), 2);
    assert.equal(
      await unlockCommand(["--stale"], place, (l) => lines.push(l), { pidAlive: () => true }),
      24,
    );
    assert.ok(existsSync(lock));
    assert.equal(
      await unlockCommand(["--stale"], place, (l) => lines.push(l), { pidAlive: () => false }),
      0,
    );
    assert.ok(!existsSync(lock));
    assert.match(
      lines.at(-1) ?? "",
      /^\[SPECSTRIDE-UNLOCK\] state=foreign owner=orchestrator .*moved-to=.*backups/,
    );
    // The workspace is free again, so a launch goes through.
    const { run } = await both(f);
    assert.equal(run.handshakeCalled, true);
  } finally {
    f.dispose();
  }
});

test("`unlock` is a verb of the front door", () => {
  assert.equal(verbRowOf("unlock")?.owner, "123");
});
