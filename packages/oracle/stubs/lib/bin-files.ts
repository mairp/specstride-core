/**
 * T044 — the stub executables of `packages/oracle/stubs/bin/`, generated from
 * the names of `stub-vocabulary.json` (F141-FR-006, F141-FR-010).
 *
 * Each executable is a node-shebang file whose only line of its own is the name
 * it was called by; everything it does is `harnessMain` of `../lib/harness.ts`,
 * or `engineMain` for the as-is engine command. So adding a harness stub is
 * adding data — a name, a calling convention and a stream format — and running
 * `writeStubBinFiles` again; the comparator and the normalizer do not change
 * (F141-FR-010).
 *
 * The files are committed, and `test/stubs/names.test.ts` reads them back off
 * disk and holds them to this generator, so a name in the data and a file in
 * `bin/` can never disagree.
 */
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { engineExecutableName, stubExecutableNames } from "./names.ts";

/** `packages/oracle/stubs/bin/`. */
export const STUB_BIN_DIR = resolve(join(dirname(dirname(fileURLToPath(import.meta.url))), "bin"));

/** The mode of a stub executable: readable and executable, never writable by all. */
export const STUB_BIN_MODE = 0o755 as const;

/** The content of one stub executable. */
export function binFileContent(name: string): string {
  const engine = engineExecutableName();
  if (name === engine) {
    return (
      `#!/usr/bin/env node\n` +
      `// Generated by stubs/lib/bin-files.ts from the name \`engineExecutable\` of\n` +
      `// packages/oracle/data/stub-vocabulary.json (T044, F141-FR-009). The engine stub\n` +
      `// stands in for the engine under the launcher, the pipeline runtime and the\n` +
      `// supervisor; the oracle names it through the switch of row 41 of the \`parity\`\n` +
      `// profile and through the search path (F141-FR-004).\n` +
      `import { harnessMain } from "../lib/harness.ts";\n` +
      `harnessMain(${JSON.stringify(name)});\n`
    );
  }
  return (
    `#!/usr/bin/env node\n` +
    `// Generated by stubs/lib/bin-files.ts from the names of\n` +
    `// packages/oracle/data/stub-vocabulary.json (T044, F141-FR-006). The only line of\n` +
    `// its own is the name this executable was called by: one implementation serves the\n` +
    `// reference and the port unchanged (§O.3, rule 3).\n` +
    `import { harnessMain } from "../lib/harness.ts";\n` +
    `harnessMain(${JSON.stringify(name)});\n`
  );
}

/** Write every stub executable. Returns the files written, in the order of the data. */
export function writeStubBinFiles(dir: string = STUB_BIN_DIR): readonly string[] {
  mkdirSync(dir, { recursive: true });
  const written: string[] = [];
  for (const name of stubExecutableNames()) {
    const file = join(dir, name);
    writeFileSync(file, binFileContent(name), "utf8");
    chmodSync(file, STUB_BIN_MODE);
    written.push(file);
  }
  return Object.freeze(written);
}

/** The files on disk that differ from what the generator would write. */
export function staleStubBinFiles(dir: string = STUB_BIN_DIR): readonly string[] {
  const stale: string[] = [];
  for (const name of stubExecutableNames()) {
    const file = join(dir, name);
    let actual = "";
    try {
      actual = readFileSync(file, "utf8");
    } catch {
      stale.push(file);
      continue;
    }
    if (actual !== binFileContent(name)) stale.push(file);
  }
  return Object.freeze(stale);
}
