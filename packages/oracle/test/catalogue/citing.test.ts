/**
 * T024 — CT-141-127 (the citing page): `packages/oracle/CITING.md` is generated
 * from the data files and is equal to `spec.md` §O.1 to §O.7 (F141-FR-027).
 *
 * Three independent witnesses:
 *
 * 1. **The page on disk is the generated page.** `CITING.md` is read off disk
 *    with `readFileSync` — not through the generator's return value — and its
 *    sha-256 is compared with the sha-256 of `renderCiting()`. A durable content
 *    hash that could not exist before the page was written is what proves the
 *    page is there and is current. `npm run oracle -- check-citing` is the same
 *    comparison as a command, and is driven here through `runCheckCiting`,
 *    including the failing case on a page that was tampered with.
 * 2. **The page is generated FROM THE DATA.** Every family id, every status,
 *    every variant, every scenario name, every pattern member, every stated end
 *    on the reference, every stub kind with every verb, and every surface id and
 *    name of `packages/oracle/data/` is looked for in the page, read out of the
 *    data files on disk. A page written by hand would fail this.
 * 3. **The page is equal to `spec.md` §O.1 to §O.7.** Where the specification
 *    tree is present, §O.1 to §O.7 are cut out of `spec.md` and the page is held
 *    to them: the seven section headings, the eight rules of §O.1, the seven
 *    rules of §O.5, the three results, the field table of §O.6, the family ids
 *    and the scenario names, the verbs and the surfaces. Where the tree is
 *    absent the comparison SKIPS with its reason, and never passes silently.
 */
import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  CITING_PAGE,
  CITING_SECTIONS,
  DECLARATION_FIELDS,
  RESULTS,
  RESULT_RULES,
  RULES_IN_SHORT,
  renderCiting,
} from "../../src/catalogue/citing.ts";
import { CITING_FILE, run, runCheckCiting, runWriteCiting } from "../../src/main.ts";

const PACKAGE = resolve(dirname(dirname(dirname(fileURLToPath(import.meta.url)))));
const ROOT = resolve(dirname(dirname(PACKAGE)));
const PAGE = join(PACKAGE, CITING_PAGE);
const SPEC = join(ROOT, "specs", "141-parity-oracle", "spec.md");

const sha256 = (text: string): string => createHash("sha256").update(text, "utf8").digest("hex");

/** The data files, read off disk here and not through the module under test. */
function dataFile<T>(name: string): T {
  return JSON.parse(readFileSync(join(PACKAGE, "data", name), "utf8")) as T;
}

/** §O.1 to §O.7 of `spec.md`, or `undefined` where the specification tree is absent. */
function citingSectionsOfTheSpecification(): string | undefined {
  if (!existsSync(SPEC)) return undefined;
  const text = readFileSync(SPEC, "utf8");
  const start = text.indexOf("### §O.1");
  assert.ok(start > 0, "spec.md holds §O.1");
  const end = text.indexOf("\n## ", start);
  assert.ok(end > start, "§O.7 is followed by a section of the specification");
  return text.slice(start, end);
}

test("T024: the page on disk is the generated page, by content hash", () => {
  assert.ok(existsSync(PAGE), `${PAGE} exists`);
  const onDisk = readFileSync(PAGE, "utf8");
  const generated = renderCiting();
  assert.equal(
    sha256(onDisk),
    sha256(generated),
    "the sha-256 of the page on disk equals the sha-256 of what the data gives now",
  );
  assert.ok(onDisk.length > 10_000, `${onDisk.length} bytes`);
  assert.ok(onDisk.endsWith("\n"), "the page ends with a newline");
  // The generator is deterministic: two renders give the same bytes, so the
  // hash above is a record and not an accident of this run.
  assert.equal(sha256(renderCiting()), sha256(generated));
  // The page says it is generated and names the command that writes it.
  assert.match(onDisk, /Generated by `npm run oracle -- write-citing`/);
  assert.match(onDisk, /check-citing/);
});

test("T024: `check-citing` passes on the page and fails on a page that was tampered with", () => {
  const good = runCheckCiting(PAGE);
  assert.equal(good.code, 0, good.lines.join("\n"));
  assert.ok(good.lines.some((l) => /agrees with packages\/oracle\/data\//.test(l)));
  assert.equal(CITING_FILE, PAGE);

  // The command of the root script reaches the same check.
  assert.equal(run(["check-citing"], ROOT).code, 0);
  assert.equal(run(["no-such-command"], ROOT).code, 2);

  // Tamper with the page, see the check fail and name the line, then put the
  // page back and see the check pass again.
  const original = readFileSync(PAGE, "utf8");
  try {
    const lines = original.split("\n");
    lines[20] = `${lines[20] ?? ""} — edited by hand`;
    writeFileSync(PAGE, lines.join("\n"));
    const bad = runCheckCiting(PAGE);
    assert.equal(bad.code, 1, "a page edited by hand fails the check");
    assert.ok(bad.lines.some((l) => /differ/.test(l)));
    assert.ok(bad.lines.some((l) => /first difference at line 21/.test(l)));
    assert.ok(bad.lines.some((l) => /edited by hand/.test(l)));
  } finally {
    writeFileSync(PAGE, original);
  }
  assert.equal(runCheckCiting(PAGE).code, 0, "the page is back as it was");
  assert.equal(sha256(readFileSync(PAGE, "utf8")), sha256(renderCiting()));

  // `write-citing` is idempotent: writing the page again changes no byte.
  const before = readFileSync(PAGE, "utf8");
  assert.equal(runWriteCiting(PAGE).code, 0);
  assert.equal(readFileSync(PAGE, "utf8"), before);
});

test("T024: every id of the data files is on the page", () => {
  const page = readFileSync(PAGE, "utf8");

  const catalogue = dataFile<{
    families: {
      id: string;
      name: string;
      status: string;
      variants: string[];
      scenarios: {
        name: string;
        members?: string[];
        scenarioOf: string;
        endOnReference?: Record<string, string>;
      }[];
    }[];
    reservedNames: { names: string }[];
    notScenarios: { asked: string }[];
  }>("fixture-catalogue.json");
  for (const family of catalogue.families) {
    assert.ok(page.includes(family.id), `${family.id} is on the page`);
    assert.ok(page.includes(family.name), `${family.id}: its name`);
    for (const variant of family.variants) assert.ok(page.includes(variant), variant);
    for (const scenario of family.scenarios) {
      assert.ok(page.includes(scenario.name), `${family.id}/${scenario.name}`);
      for (const member of scenario.members ?? []) {
        assert.ok(page.includes(member), `${family.id}/${member}`);
      }
      const end = scenario.endOnReference;
      if (end !== undefined) {
        assert.ok(page.includes(end["evidence"] ?? ""), `${family.id}/${scenario.name}: evidence`);
        assert.ok(
          page.includes(end["stopReason"] ?? ""),
          `${family.id}/${scenario.name}: stop reason`,
        );
      }
    }
  }
  assert.ok(page.includes("retired"), "the status of FX-37 is on the page");
  for (const row of catalogue.reservedNames) assert.ok(page.includes(row.names), row.names);
  for (const row of catalogue.notScenarios) assert.ok(page.includes(row.asked), row.asked);

  const vocabulary = dataFile<{
    rules: string[];
    overrunExitCode: number;
    kinds: Record<string, { verbs: string[] }>;
    harnessStubs: { harness: string; executables: string[] }[];
    engineExecutable: string;
  }>("stub-vocabulary.json");
  for (const rule of vocabulary.rules) assert.ok(page.includes(rule), rule);
  assert.ok(page.includes(String(vocabulary.overrunExitCode)), "the overrun exit code");
  for (const [kind, row] of Object.entries(vocabulary.kinds)) {
    assert.ok(page.includes(`\`${kind}\``), kind);
    for (const verb of row.verbs) assert.ok(page.includes(`\`${verb}\``), `${kind}/${verb}`);
  }
  for (const harness of vocabulary.harnessStubs) {
    assert.ok(page.includes(harness.harness), harness.harness);
    for (const executable of harness.executables) {
      assert.ok(page.includes(`\`${executable}\``), executable);
    }
  }
  assert.ok(page.includes(vocabulary.engineExecutable), vocabulary.engineExecutable);

  const surfaces = dataFile<{
    runSet: string[];
    transcriptRoles: string[];
    surfaces: { id: string; name: string }[];
  }>("surfaces.json");
  for (const surface of surfaces.surfaces) {
    assert.ok(page.includes(surface.id), surface.id);
    assert.ok(page.includes(`\`${surface.name}\``), surface.name);
  }
  for (const role of surfaces.transcriptRoles) {
    assert.ok(page.includes(`transcript.${role}`), role);
  }
  for (const name of surfaces.runSet) assert.ok(page.includes(`\`${name}\``), name);
});

test("T024: the page holds the seven sections and the prose rules of §O.1, §O.5 and §O.6", () => {
  const page = readFileSync(PAGE, "utf8");
  let previous = -1;
  for (const section of CITING_SECTIONS) {
    const at = page.indexOf(`### ${section}`);
    assert.ok(at > 0, `the page holds the section ${section}`);
    assert.ok(at > previous, `${section} comes after the section before it`);
    previous = at;
  }
  assert.equal(RULES_IN_SHORT.length, 8, "§O.1 has eight rules");
  for (const rule of RULES_IN_SHORT) assert.ok(page.includes(rule), rule.slice(0, 40));
  assert.equal(RESULT_RULES.length, 7, "§O.5 has seven rules");
  for (const rule of RESULT_RULES) assert.ok(page.includes(rule), rule.slice(0, 40));
  assert.equal(RESULTS.length, 3, "§O.5 has three results");
  for (const row of RESULTS) assert.ok(page.includes(row.meaning), row.result);
  assert.equal(DECLARATION_FIELDS.length, 3, "§O.6 has three fields");
  for (const row of DECLARATION_FIELDS) {
    assert.ok(page.includes(row.field), row.field);
    assert.ok(page.includes(row.rule), row.field);
  }
});

test("T024: the page is equal to `spec.md` §O.1 to §O.7", (t) => {
  const specification = citingSectionsOfTheSpecification();
  if (specification === undefined) {
    t.skip(
      `prerequisite missing: ${SPEC} is absent (the specification tree is local and is not in ` +
        "this checkout), so §O.1 to §O.7 cannot be compared here; " +
        "`npm run oracle -- check-citing` holds the page to packages/oracle/data/, and the " +
        "generator check of the specification holds that data to spec.md",
    );
    return;
  }
  const page = readFileSync(PAGE, "utf8");

  // The seven headings are the headings of the specification.
  for (const section of CITING_SECTIONS) {
    assert.ok(specification.includes(`### ${section}`), `spec.md holds ${section}`);
  }
  // Every prose rule the page carries is the text of the specification.
  for (const rule of RULES_IN_SHORT) {
    assert.ok(specification.includes(rule), `§O.1: ${rule.slice(0, 50)}`);
  }
  for (const rule of RESULT_RULES) {
    assert.ok(specification.includes(rule), `§O.5: ${rule.slice(0, 50)}`);
  }
  for (const row of RESULTS) {
    assert.ok(specification.includes(row.meaning), `§O.5: ${row.result}`);
  }
  for (const row of DECLARATION_FIELDS) {
    assert.ok(specification.includes(row.content), `§O.6 content: ${row.field}`);
    assert.ok(specification.includes(row.rule), `§O.6 rule: ${row.field}`);
  }

  // Every family id, scenario name, verb and surface of the page is in §O.1 to
  // §O.7, and the other way round: the page neither invents nor drops an id.
  const familyIdsOfTheSpecification = new Set(
    [...specification.matchAll(/\bFX-[0-9]{2}\b/g)].map((m) => m[0]),
  );
  const familyIdsOfThePage = new Set([...page.matchAll(/\bFX-[0-9]{2}\b/g)].map((m) => m[0]));
  assert.equal(familyIdsOfThePage.size, 40, "the page names the forty ids");
  for (const id of familyIdsOfThePage) {
    assert.ok(familyIdsOfTheSpecification.has(id), `${id} is in §O.2`);
  }
  for (const id of familyIdsOfTheSpecification) {
    assert.ok(familyIdsOfThePage.has(id), `${id} of §O.2 is on the page`);
  }

  const surfaceIds = new Set([...specification.matchAll(/\bS-[0-9]{2}\b/g)].map((m) => m[0]));
  assert.equal(surfaceIds.size, 16, "§O.4 has sixteen surfaces");
  for (const id of surfaceIds) assert.ok(page.includes(id), `${id} is on the page`);

  // The scenario names and the pattern members of the data are the names of
  // §O.2 — the generator check of the specification is what holds the data to
  // spec.md, and this assertion closes the loop from the page back to spec.md.
  const catalogue = dataFile<{
    families: { id: string; scenarios: { name: string; members?: string[] }[] }[];
  }>("fixture-catalogue.json");
  for (const family of catalogue.families) {
    for (const scenario of family.scenarios) {
      assert.ok(specification.includes(scenario.name), `§O.2: ${family.id}/${scenario.name}`);
      for (const member of scenario.members ?? []) {
        assert.ok(specification.includes(member), `§O.2: ${family.id}/${member}`);
      }
    }
  }
  const vocabulary = dataFile<{ kinds: Record<string, { verbs: string[] }> }>(
    "stub-vocabulary.json",
  );
  for (const [kind, row] of Object.entries(vocabulary.kinds)) {
    for (const verb of row.verbs) {
      assert.ok(specification.includes(`\`${verb}\``), `§O.3: ${kind}/${verb}`);
    }
  }
});
