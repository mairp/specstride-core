/**
 * T026 — static test of the rows of the `parity` profile that feature 146
 * owns (F146-FR-012; F146-FR-016; D-2 of the plan).
 *
 * Every switch of this feature has a row in the `parity` profile, and the
 * value the profile gives the switch is the value the contract of the
 * feature states: both discovery switches are `off` under `parity` (D-2, a
 * stub invocation would append a transcript record and change a compared
 * surface), and the catalogue window margin is `not used` — discovery is
 * off, so no window is read and no margin is applied.
 *
 * Two files are read, never imported: the contract of this feature
 * (`specs/146-harness-discovery/contracts/parity-rows.json`) and the parity
 * table the catalogue ships (`packages/config/data/profile-parity.json`,
 * generated by feature 110's `profile-parity-gen.ts` from the catalogue).
 * `@specstride/harness` imports neither file, and imports no code of
 * `@specstride/config`: the package graph forbids it, so the test reads the
 * shipped data as data — the same reading feature 110's own parity tests
 * apply (`packages/config/tests/parity/oracle.ts`).
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url)); // packages/harness/tests/static
// static -> tests -> harness -> packages -> repository root
const ROOT = join(HERE, "..", "..", "..", "..");

interface ContractRow {
  readonly row: number;
  readonly switch: string;
  readonly key: string;
  readonly default: string;
  readonly parity: string;
  readonly register: string;
  readonly requirement: string;
  readonly status: string;
}

interface ContractFile {
  readonly schema: string;
  readonly feature: string;
  readonly owned: readonly number[];
  readonly shared: readonly unknown[];
  readonly read: readonly number[];
  readonly rows: readonly ContractRow[];
}

interface ProfileRow {
  readonly key: string;
  readonly annexRows: readonly number[];
  readonly annexParity: readonly string[];
  readonly cell: string;
  readonly default: string;
  readonly owners: readonly string[];
  readonly sets: boolean;
  readonly value?: boolean;
  readonly literal?: string;
}

interface ProfileFile {
  readonly schema: string;
  readonly profile: string;
  readonly rows: readonly ProfileRow[];
}

const CONTRACT = JSON.parse(
  readFileSync(
    join(ROOT, "specs", "146-harness-discovery", "contracts", "parity-rows.json"),
    "utf8",
  ),
) as ContractFile;

const PROFILE = JSON.parse(
  readFileSync(join(ROOT, "packages", "config", "data", "profile-parity.json"), "utf8"),
) as ProfileFile;

/** The one row of the parity profile that carries the annex row, or null. */
function profileRowFor(annexRow: number): ProfileRow | null {
  const found = PROFILE.rows.filter((r) => r.annexRows.includes(annexRow));
  assert.equal(found.length, 1, `annex row ${annexRow}: exactly one row of the parity profile`);
  return found[0] ?? null;
}

test("T026: the contract owns exactly rows 87, 88 and 89, all confirmed, all of F146-FR-012 or F146-FR-016", () => {
  assert.equal(CONTRACT.schema, "specstride.profile/1");
  assert.equal(CONTRACT.feature, "146");
  assert.deepEqual(CONTRACT.owned, [87, 88, 89]);
  assert.deepEqual(CONTRACT.shared, []);
  for (const row of CONTRACT.rows) {
    assert.equal(row.status, "confirmed", `row ${row.row}: not confirmed`);
    assert.ok(
      row.requirement === "F146-FR-012" || row.requirement === "F146-FR-016",
      `row ${row.row}: requirement is neither F146-FR-012 nor F146-FR-016`,
    );
  }
});

test("T026: every switch of this feature has exactly one row in the `parity` profile, with the contract's key", () => {
  for (const row of CONTRACT.rows) {
    const profileRow = profileRowFor(row.row);
    assert.notEqual(profileRow, null, `row ${row.row}: no row in the parity profile`);
    assert.equal(profileRow?.key, row.key, `row ${row.row}: the key of the profile row differs`);
    assert.ok(
      profileRow?.owners.includes("146"),
      `row ${row.row}: the parity profile row is not owned by feature 146`,
    );
    assert.deepEqual(
      profileRow?.annexParity,
      [row.parity],
      `row ${row.row}: the annex states a different parity value than the contract`,
    );
  }
});

test("T026: both discovery switches take the value `off` under `parity`, as the contract states (D-2)", () => {
  for (const row of CONTRACT.rows.filter((r) => r.parity === "off")) {
    const profileRow = profileRowFor(row.row);
    assert.equal(profileRow?.cell, "off", `row ${row.row}: the profile cell is not \`off\``);
    assert.equal(profileRow?.sets, true, `row ${row.row}: the profile does not set the key`);
    assert.equal(
      profileRow?.value,
      false,
      `row ${row.row}: the value the profile sets is not the off of the switch`,
    );
    // The off is a real off: the default is not the off (D-2 asks for a
    // change, not for a restatement of the default).
    assert.notEqual(profileRow?.default, "off", `row ${row.row}: the default already is the off`);
  }
});

test("T026: the catalogue window margin is `not used` under `parity`, as the contract states", () => {
  const row = CONTRACT.rows.find((r) => r.parity === "not used");
  assert.notEqual(row, undefined, "the contract states no row of value `not used`");
  const profileRow = profileRowFor(row?.row ?? -1);
  assert.equal(profileRow?.cell, "not used", "the profile cell is not `not used`");
  assert.equal(profileRow?.sets, false, "the profile sets a key the contract leaves unused");
  assert.equal(profileRow?.literal, "not used", "the profile carries another reserved literal");
});
